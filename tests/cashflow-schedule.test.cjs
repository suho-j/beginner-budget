const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const ctx = vm.createContext({window:{}});
for (const f of ['storage','cashflow-schedule']) vm.runInContext(fs.readFileSync(__dirname+'/../js/'+f+'.js','utf8'),ctx);
const S=ctx.window.BudgetStorage, C=ctx.window.BudgetCashflowSchedule;
const item=(day,rule='next')=>({name:'테스트',kind:'fixed',amount:100,schedule:{day,rule,account:'계좌',note:''}});
assert.equal(C.dateFor('2026-10',item('10','previous').schedule),'2026-10-08');
assert.equal(C.dateFor('2026-10',item('5').schedule),'2026-10-06');
assert.equal(C.dateFor('2026-10',item('last').schedule),'2026-11-02');
assert.equal(C.dateFor('2026-02',item('31','none').schedule),'2026-02-28');
assert.equal(C.dateFor('2026-10',item('').schedule),null);
const plan={items:[item('last'),{...item('10'),kind:'transfer'}],livingBudget:0};
assert.equal(S.normalizeCashflowPlan(plan).items[0].schedule.day,'last');
assert.equal(S.summarizeCashflow(plan).committed,100);
assert.equal(S.normalizeCashflowPlan({items:[item('32')],livingBudget:0}),null);
const events=C.events({'2026-10':plan,'2026-11':{items:[item('5')],livingBudget:0}},'2026-11');
assert.equal(events.dated.length,2);
assert.equal(events.dated[0].date,'2026-11-02');
assert.equal(events.dated[0].planMonth,'2026-10');
assert.equal(C.events({'2026-10':{items:[item('')],livingBudget:0}},'2026-10').undated.length,1);
console.log('Cashflow schedule: holiday direction, spillover, unknown dates, validation and transfers passed');
